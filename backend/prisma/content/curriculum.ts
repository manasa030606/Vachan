// Units and lessons

export type ScriptLessonKind = "vowels" | "consonants" | "signs" | "reading" | "script-review";

export type LessonPlan = {
  /** Stable key, used in lesson notes and extras. */
  key: string;
  title: string;
  intro: string;
  kind: LessonKind;
  /** New words/phrases taught in this lesson. */
  items?: ConceptKey[];
  /** Words from earlier lessons practised again (reviews, distractors). */
  practice?: ConceptKey[];
  /** [what someone says, a good reply] — "pick the right reply" exercises. */
  replies?: Array<[ConceptKey, ConceptKey]>;
  dialogue?: DialogueKey;
  /** Script lessons: which part of script.ts to use (1-based group number). */
  script?: { kind: ScriptLessonKind; group?: number };
};

export type UnitPlan = {
  key: string;
  title: string;
  description: string;
  stage: LearningStage;
  lessons: LessonPlan[];
};

