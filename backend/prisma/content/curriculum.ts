const T = TOPICS;

export type ConceptDef = {
  /** English meaning. "(city)"-style placeholders must be filled in by each language's `meaning`. */
  en: string;
  topic: string;
  kind: "WORD" | "PHRASE";
  /** Extra English answers accepted for every language. */
  accept?: string[];
  /** True when the English depends on the language (e.g. a local city or the language's name). */
  localized?: boolean;
};

const w = (en: string, topic: string, accept?: string[]): ConceptDef => ({
  en,
  topic,
  kind: "WORD",
  accept,
});
const p = (en: string, topic: string, accept?: string[]): ConceptDef => ({
  en,
  topic,
  kind: "PHRASE",
  accept,
});
/** A phrase whose English must be localized by each language (e.g. "I live in Chennai."). */
const pl = (en: string, topic: string): ConceptDef => ({
  en,
  topic,
  kind: "PHRASE",
  localized: true,
});

